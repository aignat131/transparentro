UNKNOWN = "Altele / necunoscut"


def cpv_category(code: str | None) -> str:
    if not code:
        return UNKNOWN
    digits = "".join(ch for ch in code if ch.isdigit())[:8]
    for n in (5, 4, 3, 2):
        cat = _CATEGORIES.get(digits[:n])
        if cat:
            return cat
    return UNKNOWN


def all_categories() -> list[str]:
    return sorted(set(_CATEGORIES.values()) | {UNKNOWN})
